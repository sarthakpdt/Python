num1=int(input("enter the first number:"))
num2=int(input("enter the second number:"))
op=input("enter the operation u want to perform:")
if op=="+":
    print("your ans is:",num1+num2)
elif op=="-":
    print("your ans is:",num1-num2)
elif op=="*":
    print("your ans is:",num1*num2)
elif op=="/":
    print("your ans is:",num1/num2)
